create table vaccinations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    pet_id BIGINT NOT NULL,
    vaccine_name varchar(100) not null,
    vaccine_batch_number varchar(100) not null,
    application_date DATE not null,
    expiration_date DATE not null,
    next_vaccination_date DATE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT pk_vaccinations PRIMARY KEY (id),
    CONSTRAINT fk_vaccinations_pets FOREIGN KEY (pet_id) references pets(id) on delete restrict,

    CONSTRAINT chk_vaccinations_name_not_blank check (BTRIM(vaccine_name) <> ''),
    CONSTRAINT chk_vaccinations_batch_number_not_blank check (BTRIM(vaccine_batch_number) <> ''),

    CONSTRAINT chk_vaccinations_expiration_date check (expiration_date >= application_date),
    CONSTRAINT chk_vaccinations_next_vaccination_date check (
        next_vaccination_date IS NULL OR next_vaccination_date > application_date
    )
);

create index idx_vaccinations_pet_id on vaccinations(pet_id);
