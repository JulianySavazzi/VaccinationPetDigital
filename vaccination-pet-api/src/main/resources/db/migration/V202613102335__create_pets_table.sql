create table pets (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    name VARCHAR(100) NOT NULL,
    species varchar(50) NOT NULL,
    sex VARCHAR(10),
    birthdate TIMESTAMP WITH TIME ZONE NOT NULL,
    owner JSONB NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT pk_pets PRIMARY KEY (id),
    CONSTRAINT chk_pets_owner
        CHECK (
            JSONB_TYPEOF(owner) = 'object'

                AND owner ?& ARRAY['name', 'contact']

        AND JSONB_TYPEOF(owner -> 'name') = 'string'
        AND NULLIF(BTRIM(owner ->> 'name'), '') IS NOT NULL

        AND JSONB_TYPEOF(owner -> 'contact') = 'string'
        AND NULLIF(BTRIM(owner ->> 'contact'), '') IS NOT NULL
    )
);